"""PC-less Short producer: Drive Takeout footage -> one NEW packaged Short.

Ties together the Drive footage source, the used-segment ledger and the
existing production pipeline, for the scheduled cloud runner that replaces
the retired operator PC:

1. read the channel's own videos (stored youtube_videos snapshot, read-only)
2. for each loose Takeout video (too large for a zip part) and then each
   Takeout archive in the shared Drive folder (oldest first): download it
   only if its title matches a channel video and it fits the runner's free
   disk, extract only the video files of an archive, match each file to its
   channel video (never guessing)
3. order matched videos: confirmed game first, then proven games, longest
4. for the first video with an UNUSED highlight window: register a
   rights-confirmed queue job whose source_url records the exact segment,
   and run the existing highlight -> reframe -> captions -> quality gate ->
   package pipeline on it

It never uploads - publishing stays a separate, private-first step.

Game-title truthfulness: a Short's source title names a game ONLY when the
game is CONFIRMED by console-native metadata (PlayStation's own
#PS4Live/#PS5Live share tags carry the real game). A game that appears only
in an AI-written title or tags is CLAIMED, not confirmed - the channel has
known cases where capture names were wrong - so such Shorts get the neutral
"Archived gameplay" source title and the AI metadata cannot name a game.
"""

